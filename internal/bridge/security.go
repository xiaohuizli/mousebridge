package bridge

import (
	"bytes"
	"crypto/ed25519"
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/base64"
	"errors"
	"math/big"
	"time"
)

func NewKey() (string, error) {
	b := make([]byte, 32)
	_, err := rand.Read(b)
	return base64.RawURLEncoding.EncodeToString(b), err
}
func ParseKey(s string) ([]byte, error) {
	b, e := base64.RawURLEncoding.DecodeString(s)
	if e != nil || len(b) != 32 {
		return nil, errors.New("MOUSEBRIDGE_KEY must be a 32-byte key generated by keygen")
	}
	return b, nil
}
func mac(key, data []byte) []byte { h := hmac.New(sha256.New, key); h.Write(data); return h.Sum(nil) }

// TLSConfig pins the pairing group's Ed25519 public key on BOTH endpoints.
// A random 256-bit pairing key is required; human passwords are not accepted.
// TLS 1.3 supplies fresh session keys, record authentication and replay protection.
func TLSConfig(key []byte, server bool) (*tls.Config, error) {
	if len(key) != 32 {
		return nil, errors.New("pair key must contain 32 bytes")
	}
	priv := ed25519.NewKeyFromSeed(mac(key, []byte("mousebridge/v1/tls-identity")))
	pub := priv.Public().(ed25519.PublicKey)
	tmpl := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "MouseBridge pairing group"}, NotBefore: time.Date(2020, 1, 1, 0, 0, 0, 0, time.UTC), NotAfter: time.Date(2100, 1, 1, 0, 0, 0, 0, time.UTC), KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth, x509.ExtKeyUsageClientAuth}}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, pub, priv)
	if err != nil {
		return nil, err
	}
	cfg := &tls.Config{MinVersion: tls.VersionTLS13, Certificates: []tls.Certificate{{Certificate: [][]byte{der}, PrivateKey: priv}}, NextProtos: []string{"mousebridge/1"}}
	// Certificate authorities and hostnames are deliberately replaced with exact
	// pairing-key pinning. VerifyConnection is mandatory, including resumed sessions.
	cfg.InsecureSkipVerify = true
	cfg.VerifyConnection = func(cs tls.ConnectionState) error {
		if len(cs.PeerCertificates) != 1 {
			return errors.New("missing peer identity")
		}
		p, ok := cs.PeerCertificates[0].PublicKey.(ed25519.PublicKey)
		if !ok || !bytes.Equal(p, pub) {
			return errors.New("pair key mismatch")
		}
		if cs.NegotiatedProtocol != "mousebridge/1" {
			return errors.New("protocol mismatch")
		}
		return nil
	}
	if server {
		cfg.ClientAuth = tls.RequireAnyClientCert
	}
	return cfg, nil
}
